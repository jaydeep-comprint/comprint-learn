def temp_password() -> str:
    """Two random words + 2 random digits, all from a CSPRNG (`secrets`), ~22 bits."""
    first, second = secrets.choice(WORDS), secrets.choice(WORDS)
    return f"{first}-{second}-{secrets.randbelow(100):02d}"
